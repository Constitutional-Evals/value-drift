"""Run whole rounds of the loop. Every step is a subprocess, so each one gets clean GPUs, and
each step is skipped when its output already exists (rerun the same command to resume).

    # Round one from C_000, letting the base model do its own review (as Jinzhou did):
    python -m oct.loop --c0 hf/qwen3.8-27b/broad/C_000.md --runs runs/broad --rounds 1

    # Replicate round one exactly on Jinzhou's C_001 (skip the review):
    python -m oct.loop --c0 hf/.../C_000.md --runs runs/broad --rounds 1 \
        --use-constitution 1=hf/qwen3.8-27b/broad/round_001/C_001.md

    # Continue from Jinzhou's round-one model to round two:
    python -m oct.merge --stage r1/sft --out runs/broad/round_001/sft/merged
    cp hf/.../round_001/C_001.md runs/broad/round_001/
    python -m oct.loop --c0 hf/.../C_000.md --runs runs/broad --start 2 --rounds 1

Round r:  review(model_{r-1}, C_{r-1}) -> C_r;  prompts(C_r);  distill(model_{r-1}, C_r) -> DPO
          -> model_r^dpo;  introspect(model_r^dpo, C_r) -> SFT -> model_r;  eval hooks.
"""
from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
from pathlib import Path

from .common import BASE_MODEL


def run(cmd: list[str], done: Path | None) -> None:
    if done is not None and done.exists():
        print(f"[loop] skip (exists): {done}")
        return
    print("[loop] $ " + " ".join(cmd), flush=True)
    subprocess.run([sys.executable, "-m", *cmd], check=True)


def model_after(runs: Path, r: int, base: str) -> str:
    return base if r == 0 else str(runs / f"round_{r:03d}" / "sft" / "merged")


def one_round(r: int, runs: Path, c0: Path, base: str, fixed: dict[int, Path], tp: list[str],
              prompt_model: str | None, skip_eval: bool) -> None:
    rd = runs / f"round_{r:03d}"
    rd.mkdir(parents=True, exist_ok=True)
    prev_model = model_after(runs, r - 1, base)
    prev_c = c0 if r == 1 else runs / f"round_{r - 1:03d}" / f"C_{r - 1:03d}.md"
    cons = rd / f"C_{r:03d}.md"

    # 1. review
    if r in fixed and not cons.exists():
        shutil.copy(fixed[r], cons)
    run(["oct.review", "--model", prev_model, "--constitution", str(prev_c), "--out", str(rd),
         "--next-round", str(r), *tp], cons)
    # 2. prompts (generated by the round's input model unless told otherwise)
    run(["oct.prompts", "--model", prompt_model or prev_model, "--constitution", str(cons),
         "--out", str(rd), *tp], rd / "prompts.jsonl")
    # 3. DPO pairs
    run(["oct.distill", "--model", prev_model, "--constitution", str(cons), "--dir", str(rd), *tp],
        rd / "dpo_pairs.jsonl")
    # 4. DPO
    run(["oct.train", "dpo", "--model", prev_model, "--data", str(rd / "dpo_pairs.jsonl"),
         "--out", str(rd / "dpo")], rd / "dpo" / "training_complete.json")
    # 5. introspection data from the post-DPO model
    run(["oct.introspect", "--model", str(rd / "dpo" / "merged"), "--constitution", str(cons),
         "--dir", str(rd), *tp], rd / "sft.jsonl")
    # 6. SFT
    run(["oct.train", "sft", "--model", str(rd / "dpo" / "merged"), "--data", str(rd / "sft.jsonl"),
         "--out", str(rd / "sft")], rd / "sft" / "training_complete.json")
    # 7. evaluation of this round's checkpoints
    if not skip_eval:
        ckpts = [f"r{r-1}_final={prev_model}" if r > 1 else f"base={base}",
                 f"r{r}_dpo={rd/'dpo'/'merged'}", f"r{r}_sft={rd/'sft'/'merged'}"]
        run(["evals.behavior", "--checkpoints", *ckpts, "--constitutions", str(prev_c), str(cons),
             "--out", str(rd / "eval" / "behavior")], rd / "eval" / "behavior" / "summary.json")
        run(["evals.kl", "--model", str(rd / "sft" / "merged"), "--base", base,
             "--out", str(rd / "eval" / "kl.json"), *tp], rd / "eval" / "kl.json")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--c0", required=True, type=Path, help="starting constitution C_000.md")
    ap.add_argument("--runs", required=True, type=Path)
    ap.add_argument("--base", default=BASE_MODEL)
    ap.add_argument("--start", type=int, default=1)
    ap.add_argument("--rounds", type=int, default=1)
    ap.add_argument("--use-constitution", nargs="*", default=[], metavar="R=PATH",
                    help="skip round R's review and train on PATH instead")
    ap.add_argument("--prompt-model", help="model that writes trait prompts (default: round input)")
    ap.add_argument("--tp", type=int)
    ap.add_argument("--skip-eval", action="store_true")
    a = ap.parse_args()

    fixed = {int(k): Path(v) for k, v in (s.split("=", 1) for s in a.use_constitution)}
    tp = ["--tp", str(a.tp)] if a.tp else []
    for r in range(a.start, a.start + a.rounds):
        print(f"\n===== round {r} =====")
        one_round(r, a.runs, a.c0, a.base, fixed, tp, a.prompt_model, a.skip_eval)
    # the final model reviews once more, producing the next round's constitution
    last = a.start + a.rounds - 1
    nd = a.runs / f"round_{last + 1:03d}"
    run(["oct.review", "--model", model_after(a.runs, last, a.base),
         "--constitution", str(a.runs / f"round_{last:03d}" / f"C_{last:03d}.md"),
         "--out", str(nd), "--next-round", str(last + 1), *tp], nd / f"C_{last + 1:03d}.md")


if __name__ == "__main__":
    main()
