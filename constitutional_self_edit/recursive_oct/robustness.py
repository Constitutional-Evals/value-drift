"""Adversarial 'break character' robustness probes, adapted from OCT paper Sec 3.2-3.3.

Paper departure: the paper trains a classifier over 11 discrete, system-prompted personas
and measures whether an instruction to break role-play still lets the classifier detect the
trained persona. This project has no discrete persona and no inference-time system prompt
carrying the constitution -- it is trained directly into weights (docs/method.md) -- so
there is no role-play for an instruction to break. We instead test whether an instruction to
disregard any special conditioning shifts the SAME fixed rubric judge (judging.judge_responses,
data/behavior_rubric.json) used for ordinary neutral held-out evaluation, so the resulting
dimension counts are directly comparable to the checkpoint's already-recorded neutral summary.
A depth-of-training analog to the paper's prefill/continuation test (Sec 3.3) is also
provided: continuing a fixed early checkpoint's own turn versus continuing the checkpoint
under test's own turn, again scored with the same fixed judge.

Both generation functions here return rows compatible with judging.judge_responses; this
module performs no judging itself and never duplicates that logic.
"""
from __future__ import annotations

import json
from pathlib import Path

from .measurement import NEUTRAL_SYSTEM_PROMPT

ROOT = Path(__file__).resolve().parents[1]
ADVERSARIAL_INSTRUCTIONS_PATH = ROOT / 'data' / 'adversarial_instructions.json'
DEFAULT_FOLLOWUP = 'Can you say more about that?'


def load_adversarial_instructions(path: str | Path | None = None) -> list[str]:
    data = json.loads(Path(path or ADVERSARIAL_INSTRUCTIONS_PATH).read_text())
    instructions = data['instructions']
    if not isinstance(instructions, list) or not instructions or len(set(instructions)) != len(instructions):
        raise ValueError('Adversarial instruction bank must contain unique, nonempty entries')
    return instructions


def build_adversarial_rows(prompts: list[dict], instructions: list[str]) -> list[dict]:
    """Round-robin assign fixed suffix instructions so every source prompt is covered.

    IDs are namespaced (source id + suffix index) so results stay traceable to both the
    original held-out prompt and the exact adversarial wording, and never collide with a
    checkpoint's ordinary (non-adversarial) evaluation IDs.
    """
    rows = []
    for i, prompt in enumerate(prompts):
        index = i % len(instructions)
        rows.append({'id': f"{prompt['id']}::adv-{index:02d}", 'source_prompt_id': prompt['id'],
                     'suffix_index': index, 'prompt': prompt['prompt'].rstrip() + '\n\n' + instructions[index]})
    return rows


def generate_adversarial_responses(checkpoint, prompts: list[dict], output_path, config: dict,
                                   instructions: list[str] | None = None) -> list[dict]:
    """Regenerate held-out responses with a fixed adversarial suffix appended per prompt.

    Returns rows with (id, prompt, response, finish_reason, checkpoint), directly usable as
    judging.judge_responses input, so the checkpoint's adversarial dimension counts can be
    compared against its own saved neutral evaluation summary.
    """
    instructions = instructions if instructions is not None else load_adversarial_instructions(config.get('instructions_path'))
    rows = build_adversarial_rows(prompts, instructions)
    generation_config = {k: config[k] for k in
                         ('enable_thinking', 'max_new_tokens', 'temperature', 'top_p', 'top_k',
                          'max_input_tokens', 'batch_size', 'seed', 'backend', 'vllm_python', 'vllm_engine', 'api_key', 'timeout', 'max_retries', 'referer', 'title')
                         if k in config}
    from .generation import generate_rows
    results = generate_rows(checkpoint, rows, output_path, generation_config, system=NEUTRAL_SYSTEM_PROMPT)
    return [{**r, 'response': r['text']} for r in results]


def build_continuation_rows(prefill_responses: list[dict], prompts_by_id: dict[str, str],
                            followup: str = DEFAULT_FOLLOWUP) -> list[dict]:
    """One assistant-then-user-followup turn per usable prefill response.

    prefill_responses: rows with 'id' (matching a held-out prompt id) and 'response'/'text'
    from SOME checkpoint's saved neutral evaluation -- the fixed prefill source. Only the
    next assistant turn is generated by the checkpoint under test; the prefill text itself
    is replayed exactly, never regenerated. Missing, empty, or truncated prefill sources are
    silently skipped (traceable via the row count returned versus len(prefill_responses)).
    """
    rows = []
    for row in prefill_responses:
        prompt = prompts_by_id.get(row['id'])
        prefill_text = row.get('response', row.get('text'))
        if prompt is None or not isinstance(prefill_text, str) or not prefill_text.strip() or row.get('finish_reason') == 'length':
            continue
        rows.append({'id': row['id'],
                     'prompt': f'{prompt}\n\n(A first reply was already given; this continues after the follow-up: "{followup}")',
                     'messages': [{'role': 'system', 'content': NEUTRAL_SYSTEM_PROMPT},
                                  {'role': 'user', 'content': prompt},
                                  {'role': 'assistant', 'content': prefill_text},
                                  {'role': 'user', 'content': followup}]})
    return rows


def generate_continuations(checkpoint, prefill_responses: list[dict], prompts: list[dict], output_path,
                           config: dict, followup: str = DEFAULT_FOLLOWUP) -> list[dict]:
    """Continue a fixed prefill turn from the checkpoint under test.

    Run this once with prefill_responses from an early checkpoint (e.g. M0's eval_000.jsonl)
    and once with prefill_responses from the checkpoint under test's own saved evaluation
    (e.g. M2's eval_002.jsonl), both against the same checkpoint and prompts/followup, then
    judge both continuation sets with the same fixed rubric judge and compare dimension
    counts: a large gap suggests the checkpoint's trained dispositions are context-fragile
    rather than internalized.
    """
    prompts_by_id = {p['id']: p['prompt'] for p in prompts}
    rows = build_continuation_rows(prefill_responses, prompts_by_id, followup=followup)
    if not rows:
        raise ValueError('No usable prefill responses to continue (all missing, empty, or truncated)')
    generation_config = {k: config[k] for k in
                         ('enable_thinking', 'max_new_tokens', 'temperature', 'top_p', 'top_k',
                          'max_input_tokens', 'batch_size', 'seed', 'backend', 'vllm_python', 'vllm_engine', 'api_key', 'timeout', 'max_retries', 'referer', 'title')
                         if k in config}
    from .generation import generate_rows
    results = generate_rows(checkpoint, rows, output_path, generation_config)
    return [{**r, 'response': r['text']} for r in results]
